import type { BloodGroup } from "../types";

/** Recipient blood groups that a donor of each group can safely support. */
export const CAN_DONATE_TO: Record<BloodGroup, readonly BloodGroup[]> = {
  "O-": ["O-", "O+", "A-", "A+", "B-", "B+", "AB-", "AB+"],
  "O+": ["O+", "A+", "B+", "AB+"],
  "A-": ["A-", "A+", "AB-", "AB+"],
  "A+": ["A+", "AB+"],
  "B-": ["B-", "B+", "AB-", "AB+"],
  "B+": ["B+", "AB+"],
  "AB-": ["AB-", "AB+"],
  "AB+": ["AB+"],
};

/** Donor blood groups that can provide red cells to each recipient group. */
export const CAN_RECEIVE_FROM: Record<BloodGroup, readonly BloodGroup[]> = {
  "O-": ["O-"],
  "O+": ["O-", "O+"],
  "A-": ["O-", "A-"],
  "A+": ["O-", "O+", "A-", "A+"],
  "B-": ["O-", "B-"],
  "B+": ["O-", "O+", "B-", "B+"],
  "AB-": ["O-", "A-", "B-", "AB-"],
  "AB+": ["O-", "O+", "A-", "A+", "B-", "B+", "AB-", "AB+"],
};

export function canDonateTo(donorGroup: BloodGroup | null, recipientGroup: BloodGroup): boolean {
  return donorGroup !== null && CAN_DONATE_TO[donorGroup].includes(recipientGroup);
}